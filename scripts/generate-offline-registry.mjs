#!/usr/bin/env node
/**
 * Regenerate the bundled offline tool registry from the live Cambrian OpenAPI.
 *
 * The MCP used to fall back to `CAMBRIAN_METADATA_GROUPS` from the `cambrian`
 * npm package. That registry is a build-time snapshot of *that* package, so it
 * drifts whenever the API changes faster than `cambrian` publishes: 1.3.1 still
 * advertises six Solana endpoints the API removed, misses `price-current`'s
 * `token_addresses` rename, drops every `chain_id` numericEnum (so no Ethereum
 * tools project at all), and carries no exclusive numeric bounds.
 *
 * Owning the snapshot here decouples the fallback from that release cadence.
 * The live OpenAPI needs no credentials, so this runs in CI unauthenticated.
 *
 * Usage: node scripts/generate-offline-registry.mjs [--check]
 */
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const OUT = new URL('../src/generated/offline-registry.ts', import.meta.url);
const GROUPS = ['solana', 'base', 'deep42', 'risk'];

const { loadRuntimeMetadataGroup } = await import('cambrian/schema');

// A throwaway homedir keeps `cambrian`'s on-disk cache out of the snapshot, so
// we always capture what the API serves right now rather than a stale cache.
const home = mkdtempSync(join(tmpdir(), 'cambrian-registry-'));
const runtime = {
  stdout() {}, stdoutRaw() {}, stderr() {},
  fetch: globalThis.fetch,
  env: {},
  homedir: () => home,
  isTTY: false,
};

const groups = {};
for (const group of GROUPS) {
  const { metadata, status } = await loadRuntimeMetadataGroup(group, runtime);
  if (status?.lastError) {
    console.error(`FAIL ${group}: ${status.lastError}`);
    process.exit(1);
  }
  groups[group] = metadata;
}

// The published `cambrian@1.3.1` parser reads the same live spec but drops
// `exclusiveMinimum`/`exclusiveMaximum` entirely. Writing that snapshot would
// silently remove the only bounds the MCP has to restore, so refuse instead of
// shipping a degraded registry. Regenerate with a `cambrian` whose parser keeps
// them (the fix is in cambrian-cli, unpublished as of 2026-08-26).
const { listCambrianTools } = await import('cambrian/metadata');
const bounds = listCambrianTools(groups)
  .flatMap((tool) => tool.params)
  .filter((param) => param.spec.exclusiveMin !== undefined || param.spec.exclusiveMax !== undefined);
if (bounds.length === 0) {
  console.error(
    'Refusing to write: the installed `cambrian` OpenAPI parser produced no exclusive\n' +
    'numeric bounds. Published 1.3.1 does not parse them. Install a `cambrian` build\n' +
    'whose parser keeps exclusiveMinimum/exclusiveMaximum, then rerun.',
  );
  process.exit(1);
}

const banner = `// GENERATED by scripts/generate-offline-registry.mjs -- do not edit.
// Offline fallback snapshot of the live Cambrian OpenAPI tool registry.
// Regenerate with: npm run registry:generate
import type { CambrianGroup, CambrianMetadataGroup } from 'cambrian/metadata';

// Stored as a single string literal so tsc does not type-check a 77 kB object
// literal on every build.
export const OFFLINE_REGISTRY = JSON.parse(
  ${JSON.stringify(JSON.stringify(groups))},
) as Record<CambrianGroup, CambrianMetadataGroup>;
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== banner) {
    console.error('src/generated/offline-registry.ts is stale. Run: npm run registry:generate');
    process.exit(1);
  }
  console.log('offline registry is current');
} else {
  writeFileSync(OUT, banner);
  console.log(`wrote ${OUT.pathname} (${banner.length} bytes)`);
}
